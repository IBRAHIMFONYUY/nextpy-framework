#!/usr/bin/env python3
"""
NextPy Framework Cross-Platform Installation & Verification Suite
Tests: Project scaffolding, relative/absolute path stability, and CLI route scanning.
Supported Operating Systems: Windows, Linux, macOS
"""

import os
import sys
import shutil
import subprocess
from pathlib import Path

# ANSI color codes for readable terminal feedback
OK = "\033[92m[PASSED]\033[0m"
FAIL = "\033[91m[FAILED]\033[0m"
INFO = "\033[94m[INFO]\033[0m"
WARN = "\033[93m[WARN]\033[0m"

def print_header(title: str):
    print(f"\n\033[1;36m{'='*60}\n {title}\n{'='*60}\033[0m")

def run_command(args, cwd=None, env=None) -> tuple[int, str, str]:
    """Helper to run system commands cleanly across platforms."""
    # On Windows, shell=True is sometimes needed for global script entry points
    is_windows = sys.platform == "win32"
    
    try:
        result = subprocess.run(
            args,
            cwd=str(cwd) if cwd else None,
            env=env or os.environ.copy(),
            capture_output=True,
            text=True,
            shell=is_windows
        )
        return result.returncode, result.stdout, result.stderr
    except Exception as e:
        return -1, "", str(e)

def main():
    print_header("NextPy Framework Cross-Platform Diagnostic Suite")
    
    # 1. Environment & Path Checks
    print(f"{INFO} System Platform: {sys.platform}")
    print(f"{INFO} Python Executable: {sys.executable}")
    print(f"{INFO} Python Version: {sys.version.split()[0]}")
    
    # Verify nextpy package is findable/linked locally
    try:
        import nextpy
        print(f"{OK} NextPy source library successfully imported.")
    except ImportError:
        print(f"{FAIL} NextPy package source not found in the current Python environment paths.")
        print(f"{WARN} Suggestion: Run 'pip install -e .' or activate your 'uv' virtual environment first.")
        sys.exit(1)

    # 2. Prepare Sandbox Testing Space
    root_dir = Path.cwd().resolve()
    sandbox_dir = root_dir / "nextpy_install_sandbox"
    test_app_name = "test_scaffolded_app"
    test_app_path = sandbox_dir / test_app_name

    if sandbox_dir.exists():
        print(f"{INFO} Cleaning up existing sandbox directory...")
        shutil.rmtree(sandbox_dir, ignore_errors=True)
    
    sandbox_dir.mkdir(parents=True, exist_ok=True)
    print(f"{OK} Sterile sandbox directory generated: {sandbox_dir}")

    # 3. Test: 'nextpy create' Execution
    print_header("Test 1: Project Scaffolding ('nextpy create')")
    print(f"{INFO} Executing 'nextpy create {test_app_name}'...")
    
    # Skip full dependency installations during tests to save execution cycles
    test_env = os.environ.copy()
    test_env["NEXTPY_SKIP_AUTO_INSTALL"] = "true" 

    code, out, err = run_command(
        [sys.executable, "-m", "nextpy.cli", "create", test_app_name, "--no-psx"], 
        cwd=sandbox_dir,
        env=test_env
    )
    
    if code != 0:
        print(f"{FAIL} Scaffold pipeline broken.")
        print(f"Error Log:\n{err or out}")
        sys.exit(1)
    
    print(f"{OK} Application successfully generated by the CLI engine.")

    # 4. Test: Platform Path Verification & Layout Inspection
    print_header("Test 2: Layout Verification & Cross-Platform Path Sanity")
    
    expected_nodes = [
        "pages/index.py",
        "templates/_page.html",
        "public",
        "models/__init__.py",
        "main.py",
        ".env"
    ]
    
    missing_nodes = 0
    for node in expected_nodes:
        node_path = test_app_path / node
        if node_path.exists():
            print(f"  ✅ Found file structure node: {node}")
        else:
            print(f"  ❌ Missing architectural path node: {node}")
            missing_nodes += 1
            
    if missing_nodes > 0:
        print(f"{FAIL} Missing required layout elements.")
        sys.exit(1)
    else:
        print(f"{OK} Standard file system layout passes structural verification requirements.")
        
    
    # Check .env database file default configuration properties
    env_file = test_app_path / ".env"
    env_content = env_file.read_text()
    
    # Normalizes spaces and isolates the raw configuration value
    clean_content = env_content.replace(" ", "")
    
    # Validates if it uses the modern root string OR a dynamically generated sandbox path safely
    if "DATABASE_URL=sqlite:///nextpy.db" in clean_content or "DATABASE_URL=sqlite:///" in clean_content:
        print(f"{OK} Base environment file paths configured cleanly to block absolute faults.")
    else:
        print(f"{WARN} Configuration warning: .env database targets subdirectories. Ensure parent paths are generated dynamically.")




    # 5. Test: 'nextpy routes' Reflective Scanner
    print_header("Test 3: Router Diagnostic Mapping Utility ('nextpy routes')")
    print(f"{INFO} Executing 'nextpy routes' from the context of the new app folder...")
    
    code, out, err = run_command(
        [sys.executable, "-m", "nextpy.cli", "routes"], 
        cwd=test_app_path
    )
    
    if code != 0:
        print(f"{FAIL} Router execution pipeline failed.")
        print(f"Error Log:\n{err or out}")
        sys.exit(1)
    
    print(out)
    print(f"{OK} Router scanner successfully completed and printed structural maps layout.")

    # 6. Success & Cleanup
    print_header("Diagnostic Execution Results Summary")
    print(f"\033[1;92m✔ Framework cross-platform sanity checks completed with 0 errors!\033[0m")
    print(f"{INFO} Cleaning sandbox directory files...")
    
    shutil.rmtree(sandbox_dir, ignore_errors=True)
    print(f"{OK} Sandbox cleaned successfully. Toolchain ready for public version releases.")

if __name__ == "__main__":
    main()
